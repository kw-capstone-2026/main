import pandas as pd
import numpy as np

# =========================================================
# 1. 설정
# =========================================================

INPUT_PATH = "data/parquet_datas/final_merged_commercial_data_v4.parquet"
OUTPUT_PATH = "data/parquet_datas/final_merged_commercial_data_v5.parquet"

# =========================================================
# 2. 데이터 로드
# =========================================================

print("📂 parquet 로드 중...")

df = pd.read_parquet(INPUT_PATH)

print("✅ 로드 완료")
print(df.shape)

# =========================================================
# 3. 숫자형 변환
# =========================================================

numeric_cols = [
    '점포_수_y',
    '유사_업종_점포_수_y',
    '상권_전체점포_수',
    '총_아파트_세대수',
    '총_직장_인구_수',
    '당월_매출_금액',
    '당월_매출_건수'
]

for col in numeric_cols:

    if col in df.columns:

        df[col] = pd.to_numeric(
            df[col],
            errors='coerce'
        ).fillna(0)

print("✅ 숫자형 변환 완료")

# =========================================================
# 4. Density / Ratio Feature 생성
# =========================================================

print("🧠 Density Feature 생성 중...")

# ---------------------------------------------------------
# 4-1. 직장인구 대비 점포 밀도
# ---------------------------------------------------------

# 직장인구 100명당 점포 수

df['직장인구_100명당_점포수'] = np.where(
    df['총_직장_인구_수'] > 0,
    (df['점포_수_y'] / df['총_직장_인구_수']) * 100,
    0
)

# ---------------------------------------------------------
# 4-2. 아파트 세대 대비 점포 밀도
# ---------------------------------------------------------

# 아파트 100세대당 점포 수

df['아파트_100세대당_점포수'] = np.where(
    df['총_아파트_세대수'] > 0,
    (df['점포_수_y'] / df['총_아파트_세대수']) * 100,
    0
)

# ---------------------------------------------------------
# 4-3. 유사 업종 경쟁 강도
# ---------------------------------------------------------

# 전체 점포 중 유사업종 비율

df['유사업종_점포비율'] = np.where(
    df['상권_전체점포_수'] > 0,
    (df['유사_업종_점포_수_y'] / df['상권_전체점포_수']) * 100,
    0
)

# ---------------------------------------------------------
# 4-4. 직장인구 대비 유사업종 경쟁 강도
# ---------------------------------------------------------

# 직장인구 100명당 유사업종 점포 수

df['직장인구_100명당_유사업종수'] = np.where(
    df['총_직장_인구_수'] > 0,
    (df['유사_업종_점포_수_y'] / df['총_직장_인구_수']) * 100,
    0
)

# ---------------------------------------------------------
# 4-5. 매출 밀도
# ---------------------------------------------------------

# 점포당 평균 매출 (보완)

df['점포당_매출_밀도'] = np.where(
    df['점포_수_y'] > 0,
    df['당월_매출_금액'] / df['점포_수_y'],
    0
)

# ---------------------------------------------------------
# 4-6. 직장인구 대비 매출
# ---------------------------------------------------------

# 직장인구 1인당 평균 매출

df['직장인구_1인당_매출'] = np.where(
    df['총_직장_인구_수'] > 0,
    df['당월_매출_금액'] / df['총_직장_인구_수'],
    0
)

# ---------------------------------------------------------
# 4-7. 아파트 세대 대비 매출
# ---------------------------------------------------------

# 아파트 세대당 평균 매출

df['아파트세대당_매출'] = np.where(
    df['총_아파트_세대수'] > 0,
    df['당월_매출_금액'] / df['총_아파트_세대수'],
    0
)

print("✅ Density Feature 생성 완료")

# =========================================================
# 5. 무한대 처리
# =========================================================

print("🧹 inf 값 처리 중...")

replace_cols = [
    '직장인구_100명당_점포수',
    '아파트_100세대당_점포수',
    '유사업종_점포비율',
    '직장인구_100명당_유사업종수',
    '점포당_매출_밀도',
    '직장인구_1인당_매출',
    '아파트세대당_매출'
]

for col in replace_cols:

    df[col] = df[col].replace(
        [np.inf, -np.inf],
        0
    )

    df[col] = df[col].fillna(0)

print("✅ inf 처리 완료")

# =========================================================
# 6. 저장
# =========================================================

print("💾 parquet 저장 중...")

df.to_parquet(
    OUTPUT_PATH,
    index=False
)

print("🎉 저장 완료!")
print(f"📁 저장 위치: {OUTPUT_PATH}")

